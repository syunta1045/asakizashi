/**
 * 占い時代の語彙を、表示直前にセルフケア語彙へ中和する保険。
 *
 * 恒久対策はデータ生成側（INTERPRETATION_VERSION を上げて再生成）で、
 * ここはサーバー配信文に占い語彙が混じっても画面に出さない最後の防波堤。
 * 語彙ポリシーの唯一の正はこのファイル（scripts 側の生成禁止リストと二重管理しない）。
 */

// 複合語 → 単字 の順に並べる（「大吉」を「吉」より先に処理して「大おすすめ」化を防ぐ）
const REPLACEMENTS: [RegExp, string][] = [
  // 「木の気が…。」など五行の言い回しを丸ごと除去
  [/[木火土金水]の気が[^。\n]*。?/g, ""],
  // 吉凶の等級表現
  [/大吉/g, "とても良い調子"],
  [/中吉/g, "良い調子"],
  [/小吉/g, "まずまずの調子"],
  [/末吉/g, "ゆっくりの調子"],
  [/大凶/g, "控えめにしたい日"],
  // 命理・占い用語
  [/開運/g, "整える"],
  [/運勢/g, "調子"],
  [/運気/g, "調子"],
  [/占い/g, "メモ"],
  [/鑑定/g, "メモ"],
  [/命式/g, "傾向"],
  [/五行/g, "バランス"],
  [/用神/g, "補うとよいもの"],
  [/忌神/g, "控えるとよいもの"],
  [/干支/g, "生年月日"],
  [/十二支/g, "生まれ年"],
  [/相性/g, "距離感"],
  [/ラッキー/g, "整える"],
  // 単字の 吉/凶 は文脈付きに限定（吉日・吉田・凶作 などの巻き込みを防ぐ）
  [/吉です/g, "おすすめです"],
  [/吉。/g, "おすすめ。"],
  [/凶です/g, "控えめです"],
  [/凶。/g, "控えめ。"],
];

export function sanitizeDailyBody(text: string): string {
  let out = text.replace(/\r\n/g, "\n");
  for (const [re, to] of REPLACEMENTS) out = out.replace(re, to);
  return out
    .split(/\n{2,}/)
    .map((paragraph) => paragraph.replace(/\n/g, ""))
    .join("\n\n");
}

// 中和後に残ってはいけない占い語彙（テスト／開発時の検知用）
const NG_WORDS = [/大吉/, /中吉/, /小吉/, /末吉/, /大凶/, /運勢/, /開運/, /占い/, /鑑定/, /命式/, /五行/, /用神/, /忌神/, /干支/, /十二支/, /ラッキー/];

/** 中和後の本文にNG語彙が残っていれば、その語のリストを返す（空なら健全） */
export function findOccultResidue(text: string): string[] {
  return NG_WORDS.filter((re) => re.test(text)).map((re) => re.source);
}
